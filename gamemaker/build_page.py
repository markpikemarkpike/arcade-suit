#!/usr/bin/env python3
"""Glues the Game Maker together and writes it into the firmware as arcade_suit/page.h.
Run it after changing prompt.txt, any maker.* or phone.* file, or the starter games."""
import json, os, re, subprocess
here = os.path.dirname(os.path.abspath(__file__))
rd = lambda n: open(os.path.join(here, n)).read()
STARTERS = [('Funny pumpkin face', 'd4_face'), ('Trick or treat', 'd5_trick'), ('Rainbow bat', 'd6_batflap2'),
            ('Pumpkin hop', 'a4_jump'), ('Race cars', 'b4_race'), ('Fireworks', 'c2_fireworks')]
js = lambda v: json.dumps(v).replace('</', '<\\/')
thumbs = {}
try:  # Little pictures of the starter games, drawn by the real engine. Optional: needs node and web/arcade.wasm.
    thumbs = json.loads(subprocess.run(['node', os.path.join(here, '../web/thumbs.js')] + [f for _, f in STARTERS], capture_output=True, text=True, check=True).stdout)
except Exception as e:
    print('no thumbnails:', e)
starters = [dict(n=n, c=rd('games/%s.lua' % f), **({'t': thumbs[f]} if f in thumbs else {})) for n, f in STARTERS]
squash = lambda css: re.sub(r'\s*([{};:,>])\s*', r'\1', re.sub(r'/\*.*?\*/', '', css, flags=re.S)).strip()
strip = lambda code: '\n'.join(l for l in code.split('\n') if not l.lstrip().startswith('//'))
html = rd('phone.html')
html = html.replace('/*CSS*/', squash(rd('maker.css')))
html = html.replace('<!--MAKER-->', rd('maker.html').replace('<!--SETTINGS-->', rd('phone.settings.html')))
html = html.replace('/*PROMPT*/""', js(rd('prompt.txt').strip())).replace('/*STARTERS*/[]', js(starters))
html = html.replace('/*PHONE*/', strip(rd('phone.js'))).replace('/*CORE*/', strip(rd('maker.js')))
assert ')PAGE"' not in html
open(os.path.join(here, 'page.html'), 'w').write(html)
open(os.path.join(here, '../arcade_suit/page.h'), 'w').write(
    '// Generated by gamemaker/build_page.py. Do not edit.\n#pragma once\nstatic const char PAGE_HTML[] PROGMEM = R"PAGE(' + html + ')PAGE";\n')
print(len(html), 'bytes')
